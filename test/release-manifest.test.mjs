// Every key here is a throwaway P-256 (or Sparkle Ed25519) key generated by the
// test itself; no release key is read.
const execFileAsync = promisify(execFile);
const root = path.resolve(new URL("..", import.meta.url).pathname);
const tool = path.join(root, "scripts/release-manifest.mjs");
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const COMMIT = "4bc7afebc8ccaaa02c26d404b7ec1f724951e41d";

function baseEnv() {
  const env = { ...process.env };
  for (const name of Object.keys(env)) if (name.startsWith("OK_RELEASE_") || name.startsWith("ALIGHT_")) delete env[name];
  return env;
}

function packagerEnv(overrides = {}) {
  const artifactSha256 = "a".repeat(64);
  return {
    ALIGHT_VERSION: "0.6.1", ALIGHT_BUILD_NUMBER: "14", ALIGHT_RELEASE_CHANNEL: "stable", ALIGHT_MIN_SYSTEM_VERSION: "14.0",
    ALIGHT_ARCHITECTURES: "arm64 x86_64", ALIGHT_PUBLISHED_AT: "2026-10-13T12:00:00Z", ALIGHT_RELEASE_NOTES: "Notes.",
    ALIGHT_DOWNLOAD_PAGE_URL: "https://owlandkestrel.com/apps/alight",
    ALIGHT_ARTIFACT_URL: `https://updates.owlandkestrel.com/alight/releases/v0.6.1/${artifactSha256}/Alight.zip`,
    ALIGHT_ARTIFACT_SHA256: artifactSha256, ALIGHT_ARTIFACT_SIZE_BYTES: "1234",
    ALIGHT_APPCAST_URL: "https://updates.owlandkestrel.com/alight/stable/appcast.xml", ALIGHT_APPCAST_SHA256: "b".repeat(64),
    ALIGHT_SPARKLE_PUBLIC_KEY: "c".repeat(44), ALIGHT_SOURCE_COMMIT: COMMIT, ALIGHT_SOURCE_DIRTY: "false",
    ALIGHT_SOURCE_BUILD_CONFIGURATION: "release",
    ...overrides
  };
}

async function runTool(args, env) {
  return execFileAsync(process.execPath, [tool, ...args], { cwd: root, env: { ...baseEnv(), ...env } });
}

async function scratch(t) {
  const directory = await mkdtemp(path.join(os.tmpdir(), "alight-release-manifest-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  return directory;
}

async function throwawayKeyFile(directory, mode = 0o600) {
  const keys = generateKeyPairSync("ec", { namedCurve: "prime256v1" });
  const keyPath = path.join(directory, "throwaway-p256.pem");
  await writeFile(keyPath, keys.privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
  await chmod(keyPath, mode);
  return { keys, keyPath, publicKeyPem: keys.publicKey.export({ type: "spki", format: "pem" }).toString() };
}

function decodeEnvelope(envelope, publicKey) {
  const payloadBytes = Buffer.from(envelope.signedPayload, "base64url");
  const verified = verify("sha256", payloadBytes, publicKey, Buffer.from(envelope.signature.value, "base64url"));
  return { verified, payload: JSON.parse(payloadBytes.toString("utf8")) };
}

test("Alight payload declares its single macOS artifact as an archive", async () => {
  const { stdout } = await runTool(["payload", "alight"], packagerEnv());
  const payload = JSON.parse(stdout);
  assert.equal(payload.schema, "ok.product-update.v1");
  assert.equal(payload.appId, "alight");
  assert.equal(payload.bundleId, "com.owlandkestrel.alight");
  assert.equal(payload.artifacts.length, 1);
  assert.equal(payload.artifacts[0].kind, "archive");
  assert.equal(payload.artifacts[0].platform, "macos");
  assert.deepEqual(payload.artifacts[0].architectures, ["arm64", "x86_64"]);
  assert.equal(payload.source.dirty, false);
  parseProductUpdateManifest(payload);
});

test("bridge produces a signed ok.product-update.v1 that verifies with the matching public key", async (t) => {
  const directory = await scratch(t);
  const { keyPath, keys } = await throwawayKeyFile(directory);
  const bridgeEnv = packagerEnv({
    ALIGHT_ARTIFACT_URL: `https://updates.owlandkestrel.com/glideslope/releases/v0.6.1/${"a".repeat(64)}/Glideslope.zip`,
    ALIGHT_APPCAST_URL: "https://updates.owlandkestrel.com/glideslope/stable/appcast.xml", ALIGHT_RELEASE_NOTES: ""
  });
  const payloadPath = path.join(directory, "glideslope-bridge.payload.json");
  const manifestPath = path.join(directory, "glideslope-bridge.json");
  await writeFile(payloadPath, (await runTool(["payload", "bridge"], bridgeEnv)).stdout);
  const { stderr } = await runTool(["sign", payloadPath, manifestPath], { OK_RELEASE_PRIVATE_KEY_FILE: keyPath });
  assert.match(stderr, /Signed .* with ok-release-p256-v1/u);
  const envelope = JSON.parse(await readFile(manifestPath, "utf8"));
  assert.equal(envelope.schema, "ok.signed-manifest.v1");
  assert.deepEqual(envelope.publisher, { id: "owl-kestrel", name: "Owl & Kestrel", domain: "owlandkestrel.com", keyId: "ok-release-p256-v1" });
  assert.equal(envelope.signature.alg, "ECDSA_P256_SHA256_DER");
  const { verified, payload } = decodeEnvelope(envelope, keys.publicKey);
  assert.equal(verified, true);
  assert.deepEqual(payload, JSON.parse(await readFile(payloadPath, "utf8")));
  assert.equal(payload.schema, "ok.product-update.v1");
  assert.equal(payload.appId, "glideslope");
  assert.equal(payload.bundleId, "com.owlandkestrel.glideslope");
  assert.equal(payload.updateFeed.url, "https://updates.owlandkestrel.com/glideslope/stable/appcast.xml");
  assert.equal(payload.artifacts[0].kind, "archive");
  assert.equal("releaseNotes" in payload, false);
  const other = generateKeyPairSync("ec", { namedCurve: "prime256v1" });
  assert.equal(decodeEnvelope(envelope, other.publicKey).verified, false);
  parseProductUpdateManifest(payload);
});

test("key-file signing accepts an owner-only file and refuses 0644, symlinks and ambiguous configuration", async (t) => {
  const directory = await scratch(t);
  const payloadPath = path.join(directory, "payload.json");
  await writeFile(payloadPath, (await runTool(["payload", "alight"], packagerEnv())).stdout);
  const good = await throwawayKeyFile(directory);
  assert.equal((await stat(good.keyPath)).mode & 0o777, 0o600);
  const signedPath = path.join(directory, "signed.json");
  await runTool(["sign", payloadPath, signedPath], { OK_RELEASE_PRIVATE_KEY_FILE: good.keyPath });
  assert.equal(decodeEnvelope(JSON.parse(await readFile(signedPath, "utf8")), good.keys.publicKey).verified, true);

  const looseDirectory = await scratch(t);
  const loose = await throwawayKeyFile(looseDirectory, 0o644);
  const loosePath = path.join(directory, "loose.json");
  await assert.rejects(runTool(["sign", payloadPath, loosePath], { OK_RELEASE_PRIVATE_KEY_FILE: loose.keyPath }), /must be mode 0600/u);
  await assert.rejects(stat(loosePath), { code: "ENOENT" });

  const linkPath = path.join(directory, "linked-key.pem");
  await symlink(good.keyPath, linkPath);
  const linkedOutput = path.join(directory, "linked.json");
  await assert.rejects(runTool(["sign", payloadPath, linkedOutput], { OK_RELEASE_PRIVATE_KEY_FILE: linkPath }), /must not be a symbolic link/u);
  await assert.rejects(stat(linkedOutput), { code: "ENOENT" });

  await assert.rejects(runTool(["sign", payloadPath, path.join(directory, "relative.json")], { OK_RELEASE_PRIVATE_KEY_FILE: "throwaway-p256.pem" }),
    /must be an absolute path/u);
  await assert.rejects(runTool(["sign", payloadPath, path.join(directory, "both.json")], {
    OK_RELEASE_PRIVATE_KEY_FILE: good.keyPath, OK_RELEASE_PRIVATE_KEY_PEM: good.keys.privateKey.export({ type: "pkcs8", format: "pem" })
  }), /Set only one/u);
  const ed25519 = generateKeyPairSync("ed25519");
  const edPath = path.join(directory, "ed25519.pem");
  await writeFile(edPath, ed25519.privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
  await assert.rejects(runTool(["sign", payloadPath, path.join(directory, "ed.json")], { OK_RELEASE_PRIVATE_KEY_FILE: edPath }), /must be ECDSA P-256/u);
});

test("without any key the manifest stays an unsigned preview of the payload", async (t) => {
  const directory = await scratch(t);
  const payloadPath = path.join(directory, "payload.json");
  const manifestPath = path.join(directory, "manifest.json");
  await writeFile(payloadPath, (await runTool(["payload", "bridge"], packagerEnv())).stdout);
  const { stderr } = await runTool(["sign", payloadPath, manifestPath], {});
  assert.match(stderr, /unsigned preview/u);
  assert.equal(await readFile(manifestPath, "utf8"), await readFile(payloadPath, "utf8"));
  assert.equal(JSON.parse(await readFile(manifestPath, "utf8")).schema, "ok.product-update.v1");
});

// Optional cross-check against Nest's own release-origin validator, imported
// read-only from a Nest checkout: NEST_SPARKLE_PUBLICATION_MODULE=<nest>/scripts/nest-sparkle-publication.mjs
const nestModulePath = process.env.NEST_SPARKLE_PUBLICATION_MODULE || "";

function sparkleFixture({ origin, publicPath, version, build }) {
  const sparkle = generateKeyPairSync("ed25519");
  const sparklePublicKey = sparkle.publicKey.export({ format: "der", type: "spki" }).subarray(-32).toString("base64");
  const archive = Buffer.from(`archive fixture ${version} ${build}\n`);
  const archiveSha256 = sha256(archive);
  const artifactPublicPath = publicPath(archiveSha256);
  const body = Buffer.from(`<?xml version="1.0"?><rss xmlns:sparkle="http://www.andymatuschak.org/xml-namespaces/sparkle"><channel><item><sparkle:shortVersionString>${version}</sparkle:shortVersionString><sparkle:version>${build}</sparkle:version><enclosure url="${origin}${artifactPublicPath}" length="${archive.length}" sparkle:edSignature="${sign(null, archive, sparkle.privateKey).toString("base64")}" /></item></channel></rss>\n`);
  const appcast = Buffer.from(`${body}<!-- sparkle-signatures:\nedSignature: ${sign(null, body, sparkle.privateKey).toString("base64")}\nlength: ${body.length}\n-->\n`);
  return { sparklePublicKey, archive, archiveSha256, artifactPublicPath, appcast, appcastSha256: sha256(appcast) };
}

async function writeSignedManifest(directory, name, payload, keyPath) {
  const payloadPath = path.join(directory, `${name}.payload.json`);
  const manifestPath = path.join(directory, `${name}.json`);
  await writeFile(payloadPath, `${JSON.stringify(payload, null, 2)}\n`);
  await runTool(["sign", payloadPath, manifestPath], { OK_RELEASE_PRIVATE_KEY_FILE: keyPath });
  const bytes = await readFile(manifestPath);
  return { manifestPath, manifestSha256: sha256(bytes) };
}

const absentOrigin = { readPublicObject: async () => { throw Object.assign(new Error("absent"), { code: "ENOENT" }); } };

test("Nest's release-origin validator admits the signed Alight manifest", { skip: !nestModulePath && "set NEST_SPARKLE_PUBLICATION_MODULE" }, async (t) => {
  const nest = await import(nestModulePath);
  const directory = await scratch(t);
  const { keyPath, publicKeyPem } = await throwawayKeyFile(directory);
  const version = "0.6.1"; const build = 14;
  const f = sparkleFixture({ origin: nest.ALIGHT_UPDATE_ORIGIN, version, build, publicPath: (sha) => `/alight/releases/v${version}/${sha}/Alight.zip` });
  const payload = buildAlightPayload({
    version, build, channel: "stable", publishedAt: "2026-10-13T12:00:00Z", downloadPageUrl: "https://owlandkestrel.com/apps/alight",
    feedUrl: `${nest.ALIGHT_UPDATE_ORIGIN}/alight/stable/appcast.xml`, feedSha256: f.appcastSha256, sparklePublicKey: f.sparklePublicKey,
    sourceCommit: COMMIT, sourceDirty: false, buildConfiguration: "release", architectures: "arm64",
    artifactUrl: `${nest.ALIGHT_UPDATE_ORIGIN}${f.artifactPublicPath}`, artifactSha256: f.archiveSha256, artifactSizeBytes: f.archive.length
  });
  const artifactPath = path.join(directory, "Alight.zip"); const appcastPath = path.join(directory, "appcast.xml");
  await writeFile(artifactPath, f.archive); await writeFile(appcastPath, f.appcast);
  const { manifestPath, manifestSha256 } = await writeSignedManifest(directory, "alight-update", payload, keyPath);
  const input = (manifest, digest) => ({
    releaseOriginRoot: path.join(directory, "origin"), artifactPath, appcastPath, manifestPath: manifest,
    artifactPublicPath: f.artifactPublicPath, appcastPublicPath: `/alight/stable/appcasts/build-${build}-${f.appcastSha256}.xml`,
    manifestPublicPath: `/alight/stable/manifests/build-${build}-${digest}.json`, pointerPublicPath: "/alight/stable/appcast.xml",
    artifactSha256: f.archiveSha256, appcastSha256: f.appcastSha256, manifestSha256: digest, artifactSizeBytes: f.archive.length,
    version, build, channel: "stable", sourceRepository: "alight", sourceRepositoryUrl: "https://github.com/owl-and-kestrel/alight.git",
    sourceCommit: COMMIT, requestId: "alight-manifest-test", sparklePublicKey: f.sparklePublicKey, sparkleKeyId: "sparkle-glideslope-1"
  });
  const dependencies = { origin: absentOrigin, trustedSparklePublicKey: f.sparklePublicKey, trustedOkReleasePublicKeyPem: publicKeyPem };
  const prepared = await nest.prepareAlightSparklePublication(input(manifestPath, manifestSha256), dependencies);
  assert.equal(prepared.manifestSha256, manifestSha256);
  // Negative control: the pre-change payload shape (no artifact kind) is refused.
  const kindless = structuredClone(payload);
  delete kindless.artifacts[0].kind;
  const old = await writeSignedManifest(directory, "kindless", kindless, keyPath);
  await assert.rejects(nest.prepareAlightSparklePublication(input(old.manifestPath, old.manifestSha256), dependencies), { code: "manifest_binding_mismatch" });
});

// Nest admits only the fixed historical bridge identity (Glideslope 0.5.2
// build 12 from commit 9df75478…, provenance URL glideslope.git). Given that
// identity, the bridge payload's field set matches Nest's validator; the one
// remaining difference is that Alight records its true source repository.
test("Nest's bridge validator matches the bridge field set except the historical source repository", { skip: !nestModulePath && "set NEST_SPARKLE_PUBLICATION_MODULE" }, async (t) => {
  const nest = await import(nestModulePath);
  const directory = await scratch(t);
  const { keyPath, keys, publicKeyPem } = await throwawayKeyFile(directory);
  const version = "0.5.2"; const build = 12; const sourceCommit = "9df75478514deb724fdf161c1f6862bb7761e599";
  const f = sparkleFixture({ origin: nest.GLIDESLOPE_BRIDGE_UPDATE_ORIGIN, version, build, publicPath: (sha) => `/glideslope/releases/v${version}/${sha}/Glideslope.zip` });
  const payload = buildBridgePayload({
    version, build, channel: "stable", publishedAt: "2026-10-13T12:00:00Z", downloadPageUrl: "https://owlandkestrel.com/apps/alight",
    feedUrl: `${nest.GLIDESLOPE_BRIDGE_UPDATE_ORIGIN}/glideslope/stable/appcast.xml`, feedSha256: f.appcastSha256, sparklePublicKey: f.sparklePublicKey,
    sourceCommit, sourceDirty: false, buildConfiguration: "release", architectures: "arm64",
    artifactUrl: `${nest.GLIDESLOPE_BRIDGE_UPDATE_ORIGIN}${f.artifactPublicPath}`, artifactSha256: f.archiveSha256, artifactSizeBytes: f.archive.length
  });
  const artifactPath = path.join(directory, "Glideslope.zip"); const appcastPath = path.join(directory, "appcast.xml");
  await writeFile(artifactPath, f.archive); await writeFile(appcastPath, f.appcast);
  const input = (manifestPath, manifestSha256) => ({
    releaseOriginRoot: path.join(directory, "origin"), artifactPath, appcastPath, manifestPath,
    artifactPublicPath: f.artifactPublicPath, appcastPublicPath: `/glideslope/stable/appcasts/build-${build}-${f.appcastSha256}.xml`,
    manifestPublicPath: `/glideslope/stable/manifests/build-${build}-${manifestSha256}.json`, pointerPublicPath: "/glideslope/stable/appcast.xml",
    artifactSha256: f.archiveSha256, appcastSha256: f.appcastSha256, manifestSha256, artifactSizeBytes: f.archive.length,
    version, build, channel: "stable", sourceRepository: "alight", sourceRepositoryUrl: nest.GLIDESLOPE_BRIDGE_SOURCE_URL,
    sourceCommit, requestId: "bridge-manifest-test", sparklePublicKey: f.sparklePublicKey, sparkleKeyId: "sparkle-glideslope-1"
  });
  const dependencies = { origin: absentOrigin, trustedSparklePublicKey: f.sparklePublicKey, trustedOkReleasePublicKeyPem: publicKeyPem };

  const asBuilt = await writeSignedManifest(directory, "glideslope-bridge", payload, keyPath);
  await assert.rejects(nest.prepareGlideslopeBridgeSparkleRelease(input(asBuilt.manifestPath, asBuilt.manifestSha256), dependencies),
    { code: "manifest_binding_mismatch" });

  const historical = structuredClone(payload);
  historical.source.repository = nest.GLIDESLOPE_BRIDGE_SOURCE_URL;
  const historicalPath = path.join(directory, "historical-bridge.json");
  const historicalBytes = Buffer.from(`${JSON.stringify(signManifestPayload(historical, keys.privateKey), null, 2)}\n`);
  await writeFile(historicalPath, historicalBytes);
  const prepared = await nest.prepareGlideslopeBridgeSparkleRelease(input(historicalPath, sha256(historicalBytes)), dependencies);
  assert.equal(prepared.manifestSha256, sha256(historicalBytes));
});
